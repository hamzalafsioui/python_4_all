PRODUCTS = ["Electronics", "Clothing", "Home Goods"]
DAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


# ============================================================
# Analytics Functions
# ============================================================

def total_revenue(data):
    """
    Sum of all sales across stores, products, and days.
    """
    return np.sum(data)


def store_revenue(data):
    """
    Revenue generated by each store.
    Shape returned: (5,)
    """
    return np.sum(data, axis=(1, 2))


def product_revenue(data):
    """
    Revenue generated by each product category.
    Shape returned: (3,)
    """
    return np.sum(data, axis=(0, 2))


def daily_averages(data):
    """
    Average sales for each day across all stores/products.
    Shape returned: (7,)
    """
    return np.round(np.mean(data, axis=(0, 1)), 2)


def best_store(data):
    """
    Returns index of store with highest revenue.
    """
    return np.argmax(store_revenue(data))


def apply_tax(data, rate):
    """
    Deduct tax from all sales values.
    Returns a NEW array (does not modify original).
    """
    taxed_data = data * (1 - rate)
    return np.round(taxed_data, 2)


# ============================================================
# Dashboard Display
# ============================================================

def print_dashboard(data):
    print("=" * 60)
    print(" SALES DATA ANALYZER DASHBOARD ")
    print("=" * 60)

    # Total revenue
    print(f"\nTotal Revenue: ${total_revenue(data):,}")

    # Store revenue
    print("\nRevenue by Store:")
    store_totals = store_revenue(data)

    for i, revenue in enumerate(store_totals):
        print(f"  Store {i}: ${revenue:,}")

    # Product revenue
    print("\nRevenue by Product Category:")
    product_totals = product_revenue(data)

    for product, revenue in zip(PRODUCTS, product_totals):
        print(f"  {product:<12}: ${revenue:,}")

    # Daily averages
    print("\nAverage Daily Sales:")
    averages = daily_averages(data)

    for day, avg in zip(DAYS, averages):
        print(f"  {day}: ${avg}")

    # Best store
    best = best_store(data)
    print(f"\nBest Performing Store: Store {best}")

    # Tax example
    taxed = apply_tax(data, 0.08)

    print("\nSample Taxed Data (8% deduction applied):")
    print(taxed)

    print("\n" + "=" * 60)


