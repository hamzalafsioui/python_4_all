"""
PROJECT: The Sales Data Analyzer (Simulator)

Goal: Build a high-performance sales analytics simulator using NumPy.

Requirements:

1. Data Generation:
   - Imagine we have data for 5 different retail stores (Store 0 to Store 4).
   - Each store sells 3 product categories: "Electronics", "Clothing", "Home Goods".
   - We track daily sales for these products over a 7-day week.
   - This can be represented as a 3D NumPy array of shape (5, 3, 7):
     - Dimension 0: Stores (5)
     - Dimension 1: Products (3)
     - Dimension 2: Days (7)

2. Analytics Tasks (Implement using Vectorized NumPy Operations):
   - 'total_revenue(data)': Returns the sum of all sales across all stores, products, and days.
   - 'store_revenue(data)': Returns a 1D array of length 5, showing the total revenue for each store.
   - 'product_revenue(data)': Returns a 1D array of length 3, showing the total revenue for each product category across all stores.
   - 'daily_averages(data)': Returns a 1D array of length 7, showing the average sales for each day of the week.
   - 'best_store(data)': Identifies the index of the store with the highest revenue.
   - 'apply_tax(data, rate)': Returns a copy of the data with a tax rate (e.g., 0.08 for 8%) deducted from all sales.

3. Testing and Simulation:
   - Generate random sales data using np.random.randint(100, 1000, size=(5, 3, 7)) representing dollar sales.
   - Run the analytical functions and print a formatted dashboard.

Real-World Logic:
- Global corporations like Walmart or Amazon process terabytes of sales data daily. Standard Python lists would collapse under the load, but NumPy allows them to query, slice, and analyze massive volumes of financial transactions in milliseconds.
"""

import numpy as np


